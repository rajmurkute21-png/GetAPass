/**
 * GetAPass — Authoritative Real-Time QR Verification Engine
 *
 * Implements atomic turnstile pass validation against Cloud Firestore:
 * - Atomic check-in transactions preventing duplicate entry race conditions across multiple turnstiles
 * - Web Audio API synthesizers for real-time success chime and failure buzz
 * - Native haptic vibration feedback for mobile gate staff
 * - Granular failure categorization:
 *   • INVALID_QR_CODE
 *   • PASS_NOT_FOUND
 *   • PAYMENT_NOT_COMPLETED
 *   • PASS_EXPIRED
 *   • PASS_CANCELLED
 *   • PASS_ALREADY_USED (with historical timestamp, gate, and verifier info)
 *   • UNAUTHORIZED_VERIFIER
 *   • PASS_DOES_NOT_BELONG_TO_THIS_EVENT
 * - Immutable turnstile audit trail logged to `/checkIns`
 * - Resilient offline verification fallback
 */

import { doc, getDoc, updateDoc, runTransaction, query, collection, where, getDocs } from 'firebase/firestore';
import { db } from '../config/firebase.js';
import { COLLECTIONS, STATUS_ENUMS, generateDocId } from '../constants/firestoreSchema.js';
import { canValidatePasses } from './permissionService.js';
import { recordCheckInAuditLog, verifyPassOffline, queueOfflineCheckin } from './verifierService.js';
import {
  getStoredUserPasses,
  saveStoredUserPasses,
  getStoredUserBookings,
  saveStoredUserBookings
} from './bookingService.js';

// Canonical Verification Result Codes
export const VERIFICATION_CODES = {
  VALID: 'VALID_PASS',
  INVALID_QR: 'INVALID_QR_CODE',
  PASS_NOT_FOUND: 'PASS_NOT_FOUND',
  PAYMENT_NOT_COMPLETED: 'PAYMENT_NOT_COMPLETED',
  PASS_EXPIRED: 'PASS_EXPIRED',
  PASS_CANCELLED: 'PASS_CANCELLED',
  PASS_ALREADY_USED: 'PASS_ALREADY_USED',
  UNAUTHORIZED_VERIFIER: 'UNAUTHORIZED_VERIFIER',
  WRONG_EVENT: 'PASS_DOES_NOT_BELONG_TO_THIS_EVENT'
};

export const VERIFICATION_TITLES = {
  [VERIFICATION_CODES.VALID]: 'VALID PASS',
  [VERIFICATION_CODES.INVALID_QR]: 'INVALID QR CODE',
  [VERIFICATION_CODES.PASS_NOT_FOUND]: 'PASS NOT FOUND',
  [VERIFICATION_CODES.PAYMENT_NOT_COMPLETED]: 'PAYMENT NOT COMPLETED',
  [VERIFICATION_CODES.PASS_EXPIRED]: 'PASS EXPIRED',
  [VERIFICATION_CODES.PASS_CANCELLED]: 'PASS CANCELLED',
  [VERIFICATION_CODES.PASS_ALREADY_USED]: 'PASS ALREADY USED',
  [VERIFICATION_CODES.UNAUTHORIZED_VERIFIER]: 'UNAUTHORIZED VERIFIER',
  [VERIFICATION_CODES.WRONG_EVENT]: 'PASS DOES NOT BELONG TO THIS EVENT'
};

// In-flight concurrency lock to prevent simultaneous submissions from the same terminal
const inFlightPassLocks = new Set();

/**
 * Parses and extracts pass identifier from diverse QR code payload formats:
 * - Structured JSON generated by Ticket3D: {"passId":"GP-...","bookingId":"...","event":"...","attendee":"..."}
 * - Plain string Pass IDs: "GP-TF26-9481-1", "pass_12345"
 * - URLs containing passId or id parameters
 */
export function parseQRPayload(rawData) {
  if (!rawData) return null;
  const trimmed = String(rawData).trim();
  if (!trimmed) return null;

  // 1. Try parsing JSON format
  try {
    if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
      const parsed = JSON.parse(trimmed);
      const passId = parsed.passId || parsed.id || parsed.ticketId || null;
      if (passId) {
        return {
          passId: String(passId).trim(),
          bookingId: parsed.bookingId || null,
          event: parsed.event || parsed.eventTitle || null,
          attendee: parsed.attendee || parsed.attendeeName || parsed.participant || null,
          authority: parsed.authority || null,
          status: parsed.status || null,
          isJson: true,
          raw: trimmed
        };
      }
    }
  } catch {
    // Non-JSON or malformed JSON
  }

  // 2. Query parameter or URL containing passId
  if (trimmed.includes('passId=')) {
    const match = trimmed.match(/passId=([a-zA-Z0-9_\-.:]+)/);
    if (match && match[1]) {
      return { passId: match[1].trim(), isJson: false, raw: trimmed };
    }
  }

  // 3. Raw alphanumeric / standard ticket code format
  // Accepts standard GetAPass formats: "GP-...", "BK-...", "pass_...", alphanumeric tokens
  if (/^[a-zA-Z0-9_\-.:]{3,120}$/.test(trimmed)) {
    return {
      passId: trimmed,
      isJson: false,
      raw: trimmed
    };
  }

  // If payload is malformed or unidentifiable
  return {
    passId: null,
    isJson: false,
    raw: trimmed,
    malformed: true
  };
}

/**
 * Plays real-time audio chimes via browser Web Audio API:
 * - 'success': Crisp two-tone ascending major chime (587.33Hz D5 -> 880Hz A5)
 * - 'error': Dissonant descending sawtooth buzz (220Hz -> 140Hz)
 */
export function playVerificationChime(type = 'success') {
  if (typeof window === 'undefined') return;
  try {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextClass) return;
    const ctx = new AudioContextClass();
    const now = ctx.currentTime;

    if (type === 'success') {
      // 1. First ascending tone (D5 ~587.33Hz)
      const osc1 = ctx.createOscillator();
      const gain1 = ctx.createGain();
      osc1.type = 'sine';
      osc1.frequency.setValueAtTime(587.33, now);
      gain1.gain.setValueAtTime(0.18, now);
      gain1.gain.exponentialRampToValueAtTime(0.001, now + 0.32);
      osc1.connect(gain1);
      gain1.connect(ctx.destination);
      osc1.start(now);
      osc1.stop(now + 0.32);

      // 2. Second ascending chime (A5 ~880Hz)
      const osc2 = ctx.createOscillator();
      const gain2 = ctx.createGain();
      osc2.type = 'sine';
      osc2.frequency.setValueAtTime(880, now + 0.12);
      gain2.gain.setValueAtTime(0.22, now + 0.12);
      gain2.gain.exponentialRampToValueAtTime(0.001, now + 0.58);
      osc2.connect(gain2);
      gain2.connect(ctx.destination);
      osc2.start(now + 0.12);
      osc2.stop(now + 0.58);
    } else {
      // Dissonant descending buzz
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = 'sawtooth';
      osc.frequency.setValueAtTime(220, now);
      osc.frequency.linearRampToValueAtTime(130, now + 0.38);
      gain.gain.setValueAtTime(0.24, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.42);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start(now);
      osc.stop(now + 0.42);
    }
  } catch (err) {
    // Safe fallthrough if browser blocks audio autoplay before gesture
  }
}

/**
 * Triggers hardware haptic vibration feedback on supported mobile devices
 */
export function triggerVerificationHaptic(type = 'success') {
  if (typeof navigator === 'undefined' || !navigator.vibrate) return;
  try {
    if (type === 'success') {
      navigator.vibrate([70, 40, 90]);
    } else {
      navigator.vibrate([220, 90, 220]);
    }
  } catch {
    // Ignore unsupported vibration
  }
}

/**
 * Authoritative, atomic Pass Verification & Check-in.
 * Validates pass status, payment confirmation, event matching, and verifier permissions.
 * Executes atomic Firestore transaction to prevent duplicate check-ins across concurrent gates.
 */
export async function verifyAndCheckInPassAuthoritative({
  passDataOrCode,
  currentEventId = null,
  verifierUser = null,
  gate = 'Gate A',
  isOfflineMode = false
}) {
  const parsed = parseQRPayload(passDataOrCode);
  const now = Date.now();

  // 1. Validation Check: Unrecognized / Malformed QR Code
  if (!parsed || !parsed.passId || parsed.malformed) {
    playVerificationChime('error');
    triggerVerificationHaptic('error');
    return {
      valid: false,
      code: VERIFICATION_CODES.INVALID_QR,
      title: VERIFICATION_TITLES[VERIFICATION_CODES.INVALID_QR],
      reason: 'Unrecognized QR code payload or unreadable ticket signature.',
      passId: parsed?.raw || 'Unknown',
      timestamp: now,
      gate
    };
  }

  const passId = parsed.passId;

  // 2. Validation Check: Role & Permission Authorization
  if (!canValidatePasses(verifierUser)) {
    playVerificationChime('error');
    triggerVerificationHaptic('error');
    return {
      valid: false,
      code: VERIFICATION_CODES.UNAUTHORIZED_VERIFIER,
      title: VERIFICATION_TITLES[VERIFICATION_CODES.UNAUTHORIZED_VERIFIER],
      reason: 'Unauthorized: Only event organizers, assigned verifiers, or platform administrators can validate passes.',
      passId,
      timestamp: now,
      gate
    };
  }

  // Concurrency Lock: Prevent multiple in-flight requests for the exact same pass from this client
  if (inFlightPassLocks.has(passId)) {
    return {
      valid: false,
      code: VERIFICATION_CODES.PASS_ALREADY_USED,
      title: VERIFICATION_TITLES[VERIFICATION_CODES.PASS_ALREADY_USED],
      reason: 'Pass is currently being processed at another scanner. Duplicate attempt blocked.',
      passId,
      timestamp: now,
      gate
    };
  }
  inFlightPassLocks.add(passId);

  try {
    // 3. Online Firebase Verification with Atomic Transaction
    if (!isOfflineMode && db) {
      try {
        // Find document reference: first check /passes, then fallback to /bookings
        let targetDocRef = doc(db, COLLECTIONS.PASSES, passId);
        let targetDocSnap = await getDoc(targetDocRef);
        let isDedicatedPassDoc = targetDocSnap.exists();
        let parentBookingData = null;

        if (!isDedicatedPassDoc) {
          // Check if passId matches a booking doc ID
          const bookingRef = doc(db, COLLECTIONS.BOOKINGS, passId);
          const bookingSnap = await getDoc(bookingRef);
          if (bookingSnap.exists()) {
            targetDocRef = bookingRef;
            parentBookingData = bookingSnap.data();
          } else {
            // Search /bookings where passId matches or passIds array contains passId
            const qPass = query(collection(db, COLLECTIONS.BOOKINGS), where('passId', '==', passId));
            let passDocs = await getDocs(qPass);
            if (passDocs.empty) {
              const qPassIds = query(collection(db, COLLECTIONS.BOOKINGS), where('passIds', 'array-contains', passId));
              passDocs = await getDocs(qPassIds);
            }
            if (!passDocs.empty) {
              targetDocRef = passDocs.docs[0].ref;
              parentBookingData = passDocs.docs[0].data();
            }
          }
        }

        // Run Atomic Transaction to prevent concurrent turnstile duplicate scans
        const txResult = await runTransaction(db, async (txn) => {
          const freshSnap = await txn.get(targetDocRef);
          if (!freshSnap.exists()) {
            return {
              error: true,
              code: VERIFICATION_CODES.PASS_NOT_FOUND,
              title: VERIFICATION_TITLES[VERIFICATION_CODES.PASS_NOT_FOUND],
              reason: `Pass "${passId}" not found in digital registry.`
            };
          }

          const rawDocData = freshSnap.data();
          let passItem = rawDocData;

          // If document was from /bookings, find the specific pass inside its passes array
          if (!isDedicatedPassDoc && Array.isArray(rawDocData.passes)) {
            passItem = rawDocData.passes.find(
              (p) => p.passId === passId || p.id === passId
            ) || rawDocData.passes[0];
          } else if (!isDedicatedPassDoc && rawDocData.pass) {
            passItem = rawDocData.pass;
          }

          // A. Status Check: Cancelled, Refunded, or Suspended
          const currentStatus = String(passItem.status || '').toLowerCase();
          if (currentStatus === 'cancelled' || currentStatus === 'refunded' || currentStatus === 'suspended') {
            return {
              error: true,
              code: VERIFICATION_CODES.PASS_CANCELLED,
              title: VERIFICATION_TITLES[VERIFICATION_CODES.PASS_CANCELLED],
              reason: `Pass has been ${passItem.status || 'Cancelled'} by event administration. Entry strictly denied.`,
              pass: passItem
            };
          }

          // B. Payment Status Check
          const paymentStatus = String(passItem.paymentStatus || rawDocData.paymentStatus || '').toUpperCase();
          if (paymentStatus === 'FAILED' || paymentStatus === 'DECLINED' || paymentStatus === 'PENDING' || paymentStatus === 'UNPAID' || currentStatus === 'pending payment') {
            return {
              error: true,
              code: VERIFICATION_CODES.PAYMENT_NOT_COMPLETED,
              title: VERIFICATION_TITLES[VERIFICATION_CODES.PAYMENT_NOT_COMPLETED],
              reason: `Payment verification incomplete (Status: ${paymentStatus || 'Pending'}). Pass is not valid for entry.`,
              pass: passItem
            };
          }

          // C. Expiration Check
          const validUntil = Number(passItem.validUntil || 0);
          if (currentStatus === 'expired' || (validUntil > 0 && validUntil < now)) {
            return {
              error: true,
              code: VERIFICATION_CODES.PASS_EXPIRED,
              title: VERIFICATION_TITLES[VERIFICATION_CODES.PASS_EXPIRED],
              reason: `Pass validity expired on ${new Date(validUntil || passItem.date).toLocaleDateString()}. Entry denied.`,
              pass: passItem
            };
          }

          // D. Event Matching Check
          const passEventId = passItem.eventId || rawDocData.eventId;
          if (currentEventId && passEventId && passEventId !== currentEventId) {
            return {
              error: true,
              code: VERIFICATION_CODES.WRONG_EVENT,
              title: VERIFICATION_TITLES[VERIFICATION_CODES.WRONG_EVENT],
              reason: `Pass belongs to "${passItem.eventTitle || rawDocData.eventTitle || passEventId}", not the event selected at this gate.`,
              pass: passItem
            };
          }

          // E. Duplicate Scan Check (Already Checked In)
          if (passItem.checkedIn === true || currentStatus === 'used') {
            return {
              error: true,
              code: VERIFICATION_CODES.PASS_ALREADY_USED,
              title: VERIFICATION_TITLES[VERIFICATION_CODES.PASS_ALREADY_USED],
              reason: 'Pass has already been used for gate entry. Duplicate admission blocked.',
              alreadyUsed: true,
              checkedInAt: passItem.checkedInAt || rawDocData.checkedInAt || null,
              checkedInGate: passItem.gate || passItem.checkedInGate || rawDocData.gate || 'Gate A',
              checkedInBy: passItem.verifierName || passItem.checkedInBy || 'Gate Staff',
              pass: passItem
            };
          }

          // F. All Checks Passed — Perform Atomic Check-In
          const checkinStamp = {
            checkedIn: true,
            status: STATUS_ENUMS.PASS.USED,
            checkedInAt: now,
            checkedInBy: verifierUser?.uid || 'verifier',
            verifierName: verifierUser?.displayName || verifierUser?.name || 'Gate Verifier',
            gate,
            updatedAt: now
          };

          if (isDedicatedPassDoc) {
            txn.update(targetDocRef, checkinStamp);
          } else if (Array.isArray(rawDocData.passes)) {
            const updatedPasses = rawDocData.passes.map((p) =>
              p.passId === passId || p.id === passId ? { ...p, ...checkinStamp } : p
            );
            txn.update(targetDocRef, { passes: updatedPasses, updatedAt: now });
          } else {
            txn.update(targetDocRef, checkinStamp);
          }

          return {
            error: false,
            pass: { ...passItem, ...checkinStamp }
          };
        });

        // 3a. Handle Rejections from Transaction
        if (txResult.error) {
          playVerificationChime('error');
          triggerVerificationHaptic('error');

          // Log failure audit entry
          await recordCheckInAuditLog({
            passId,
            bookingId: txResult.pass?.bookingId || null,
            eventId: txResult.pass?.eventId || currentEventId,
            eventTitle: txResult.pass?.eventTitle || 'Campus Event',
            attendeeName: txResult.pass?.attendeeName || txResult.pass?.participantName || 'Attendee',
            participantUid: txResult.pass?.participantUid || null,
            organizerUid: txResult.pass?.organizerUid || null,
            verifierUid: verifierUser?.uid,
            verifierName: verifierUser?.displayName || verifierUser?.name,
            gate,
            status: txResult.alreadyUsed ? STATUS_ENUMS.CHECK_IN.DUPLICATE : STATUS_ENUMS.CHECK_IN.DENIED,
            reason: txResult.reason
          }).catch(() => {});

          return {
            valid: false,
            code: txResult.code,
            title: txResult.title,
            reason: txResult.reason,
            passId,
            attendeeName: txResult.pass?.attendeeName || txResult.pass?.participantName || 'Attendee',
            eventTitle: txResult.pass?.eventTitle || 'Campus Event',
            category: txResult.pass?.passType || txResult.pass?.category || 'Standard',
            alreadyUsed: Boolean(txResult.alreadyUsed),
            checkedInAt: txResult.checkedInAt,
            checkedInGate: txResult.checkedInGate,
            checkedInBy: txResult.checkedInBy,
            timestamp: now,
            gate
          };
        }

        // 3b. Success Path: Pass Authorized
        const validatedPass = txResult.pass;

        // Synchronize parent booking if pass was in dedicated /passes collection
        if (isDedicatedPassDoc && validatedPass.bookingId) {
          try {
            const parentBookingRef = doc(db, COLLECTIONS.BOOKINGS, validatedPass.bookingId);
            const parentBookingSnap = await getDoc(parentBookingRef);
            if (parentBookingSnap.exists()) {
              const bData = parentBookingSnap.data();
              if (Array.isArray(bData.passes)) {
                const updatedPasses = bData.passes.map((p) =>
                  p.passId === passId || p.id === passId
                    ? {
                        ...p,
                        checkedIn: true,
                        status: STATUS_ENUMS.PASS.USED,
                        checkedInAt: now,
                        gate
                      }
                    : p
                );
                await updateDoc(parentBookingRef, { passes: updatedPasses, updatedAt: now });
              }
            }
          } catch (syncErr) {
            console.warn('[GateApass Verifier] Booking sync notice:', syncErr);
          }
        }

        // Synchronize local storage user caches for instant zero-latency UI reflection
        if (validatedPass.participantUid) {
          const userPasses = getStoredUserPasses(validatedPass.participantUid);
          const updatedUserPasses = userPasses.map((p) =>
            p.passId === passId || p.id === passId
              ? { ...p, checkedIn: true, status: STATUS_ENUMS.PASS.USED, checkedInAt: now, gate }
              : p
          );
          saveStoredUserPasses(validatedPass.participantUid, updatedUserPasses);

          const userBookings = getStoredUserBookings(validatedPass.participantUid);
          const updatedUserBookings = userBookings.map((b) => {
            if (b.bookingId === validatedPass.bookingId && Array.isArray(b.passes)) {
              return {
                ...b,
                passes: b.passes.map((p) =>
                  p.passId === passId || p.id === passId
                    ? { ...p, checkedIn: true, status: STATUS_ENUMS.PASS.USED, checkedInAt: now, gate }
                    : p
                )
              };
            }
            return b;
          });
          saveStoredUserBookings(validatedPass.participantUid, updatedUserBookings);
        }

        // Record immutable audit log in `/checkIns`
        await recordCheckInAuditLog({
          passId,
          bookingId: validatedPass.bookingId || null,
          eventId: validatedPass.eventId || currentEventId,
          eventTitle: validatedPass.eventTitle || 'Campus Event',
          attendeeName: validatedPass.attendeeName || validatedPass.participantName || 'Attendee',
          participantUid: validatedPass.participantUid || null,
          organizerUid: validatedPass.organizerUid || null,
          verifierUid: verifierUser?.uid,
          verifierName: verifierUser?.displayName || verifierUser?.name,
          gate,
          status: STATUS_ENUMS.CHECK_IN.GRANTED,
          reason: 'Pass Verified Successfully'
        }).catch(() => {});

        playVerificationChime('success');
        triggerVerificationHaptic('success');

        return {
          valid: true,
          code: VERIFICATION_CODES.VALID,
          title: VERIFICATION_TITLES[VERIFICATION_CODES.VALID],
          message: 'Pass Verified Successfully',
          entryStatus: 'APPROVED',
          passId,
          attendeeName: validatedPass.attendeeName || validatedPass.participantName || 'Attendee',
          eventTitle: validatedPass.eventTitle || 'Campus Event',
          category: validatedPass.passType || validatedPass.category || 'Standard Pass',
          gate,
          timestamp: now,
          authority: validatedPass.authority || 'Participant',
          bookingId: validatedPass.bookingId || null,
          rawPass: validatedPass
        };
      } catch (firestoreErr) {
        console.warn('[GateApass Verifier] Firestore verification error, falling back to local roster:', firestoreErr);
      }
    }

    // 4. Offline Fallback Verification Mode
    const offlineResult = verifyPassOffline(passId, currentEventId);

    if (offlineResult.valid) {
      playVerificationChime('success');
      triggerVerificationHaptic('success');

      queueOfflineCheckin({
        passId,
        eventId: currentEventId,
        gate,
        verifierUid: verifierUser?.uid,
        timestamp: now,
        status: STATUS_ENUMS.CHECK_IN.GRANTED
      });

      return {
        valid: true,
        code: VERIFICATION_CODES.VALID,
        title: VERIFICATION_TITLES[VERIFICATION_CODES.VALID],
        message: 'Pass Verified Successfully (Offline Cache)',
        entryStatus: 'APPROVED',
        passId,
        attendeeName: offlineResult.attendeeName || 'Attendee',
        eventTitle: offlineResult.eventTitle || 'Campus Event',
        category: offlineResult.passType || 'Standard Pass',
        gate,
        timestamp: now,
        authority: offlineResult.pass?.authority || 'Participant',
        offline: true
      };
    } else {
      playVerificationChime('error');
      triggerVerificationHaptic('error');

      let rejectionCode = VERIFICATION_CODES.PASS_NOT_FOUND;
      if (offlineResult.status === 'Already-used') rejectionCode = VERIFICATION_CODES.PASS_ALREADY_USED;
      else if (offlineResult.status === 'Wrong-event') rejectionCode = VERIFICATION_CODES.WRONG_EVENT;
      else if (offlineResult.status === 'Cancelled') rejectionCode = VERIFICATION_CODES.PASS_CANCELLED;
      else if (offlineResult.status === 'Expired') rejectionCode = VERIFICATION_CODES.PASS_EXPIRED;
      else if (offlineResult.status === 'Payment-pending') rejectionCode = VERIFICATION_CODES.PAYMENT_NOT_COMPLETED;

      return {
        valid: false,
        code: rejectionCode,
        title: VERIFICATION_TITLES[rejectionCode] || 'ENTRY DENIED',
        reason: offlineResult.reason || 'Offline pass verification failed.',
        passId,
        alreadyUsed: offlineResult.status === 'Already-used',
        timestamp: now,
        gate,
        offline: true
      };
    }
  } finally {
    // Release in-flight lock after a short buffer
    setTimeout(() => {
      inFlightPassLocks.delete(passId);
    }, 1200);
  }
}
